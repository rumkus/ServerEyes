// Obtener idioma guardado o detectar del navegador
function SE_getLang() {
  const saved = localStorage.getItem('se_lang');
  if (saved && SE_LANGS[saved]) return saved;
  const browser = (navigator.language || 'es').substring(0, 2);
  return SE_LANGS[browser] ? browser : 'es';
}

let SE_CURRENT_LANG = SE_getLang();

function t(key) {
  return (SE_LANGS[SE_CURRENT_LANG] && SE_LANGS[SE_CURRENT_LANG][key]) || SE_LANGS.es[key] || key;
}

function setLang(lang) {
  SE_CURRENT_LANG = lang;
  localStorage.setItem('se_lang', lang);
}

function getLangList() {
  return Object.entries(SE_LANGS).map(([code, data]) => ({ code, name: data.name, flag: data.flag }));
}
